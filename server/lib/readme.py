"""Build a cruise's README from a Jinja2 template.

The README describes the cruise and its data directory layout for whoever
opens the cruise data package later: the cruise details, the folder of each
enabled collection system and extra directory with its long name and
description, the layout of each lowering's folder, and OpenVDM's own files
(the cruise config, MD5 summary and data dashboard manifest). The cruise
worker writes it whenever it exports the cruise config (#431).

The template and file name are set by the ``cruiseReadme`` block of
``openvdm.yaml`` (:func:`readme_settings`); the variables a template can use
are described in :func:`build_cruise_readme_context`. OpenVDM starts the file
with a line saying it's generated (:data:`GENERATED_MARKER`) and won't
overwrite a file without that line, so a README that a collection system or a
person put at the top of the cruise directory is kept.
"""

import json
import logging
import os
import re
from datetime import datetime, timezone
from typing import Optional

import jinja2

# The OpenVDM checkout: server/lib/readme.py -> the repository root
OPENVDM_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.realpath(__file__))))

DEFAULT_README_FN = 'README.md'
DEFAULT_TEMPLATE = 'server/etc/cruise_readme.md.j2'

# Text in the README's first line that marks it as written by OpenVDM
GENERATED_MARKER = 'Generated by OpenVDM'

# The fields of a collection system or extra directory that a template sees;
# the API's records also carry credentials, which must never reach it
DIRECTORY_FIELDS = ('name', 'longName', 'description')


def readme_settings(config: dict) -> dict:
    """Return the README settings from the ``cruiseReadme`` block of ``openvdm.yaml``.

    Without the block (``openvdm.yaml`` files from before 2.17), the README
    is written as ``README.md`` from the default template. A relative
    template path is relative to the OpenVDM directory. When the template
    doesn't exist but its ``.dist`` does, the ``.dist`` is used, so the
    default template works before a site makes its own copy.

    Args:
        config: The parsed ``openvdm.yaml`` (``OpenVDM.config``).

    Returns:
        dict: ``enable`` (bool), ``filename`` (the README's name in the
        cruise directory) and ``template`` (absolute path of the template to
        use).

    Raises:
        ValueError: If the file name isn't a plain file name, or neither the
            template nor its ``.dist`` exists.
    """
    block = config.get('cruiseReadme')
    block = block if isinstance(block, dict) else {}

    enable = block.get('enable', True)
    enable = enable if isinstance(enable, bool) else str(enable).strip().lower() not in ('false', 'no', 'off', '0')

    filename = str(block.get('filename') or DEFAULT_README_FN).strip()
    if os.path.basename(filename) != filename or filename in ('.', '..'):
        raise ValueError(f"cruiseReadme filename must be a file name, not a path: {filename}")

    template = str(block.get('template') or DEFAULT_TEMPLATE).strip()
    if not os.path.isabs(template):
        template = os.path.join(OPENVDM_ROOT, template)
    if not os.path.isfile(template):
        if os.path.isfile(template + '.dist'):
            template += '.dist'
        else:
            raise ValueError(f"README template not found: {template}")

    return {'enable': enable, 'filename': filename, 'template': template}


def openvdm_version() -> str:
    """Return the OpenVDM version, from ``www/package.json``.

    Returns:
        str: e.g. ``'2.17.0'``, or ``''`` if it can't be read.
    """
    try:
        with open(os.path.join(OPENVDM_ROOT, 'www', 'package.json'), encoding='utf-8') as file:
            return str(json.load(file).get('version', ''))
    except (OSError, ValueError, AttributeError):
        return ''


def _fill_path(path: str, cruise_id: str, lowering_data_base_dir: str) -> str:
    """Fill in a destination directory's placeholders and drop surrounding slashes.

    ``{loweringID}`` becomes ``<loweringID>``, since the README describes
    every lowering, not one.
    """
    path = (path or '').replace('{cruiseID}', cruise_id)
    path = path.replace('{loweringDataBaseDir}', lowering_data_base_dir)
    path = path.replace('{loweringID}', '<loweringID>')
    return path.strip('/')


def _directories(entries: list, cruise_or_lowering: int, cruise_id: str,
                 lowering_data_base_dir: str) -> list:
    """Return the enabled cruise- or lowering-level entries as template dicts.

    Args:
        entries: Collection system transfers or extra directories from the
            OpenVDM API.
        cruise_or_lowering: ``0`` for cruise-level entries, ``1`` for
            lowering-level ones.
        cruise_id: The cruise ID, for ``{cruiseID}`` in paths.
        lowering_data_base_dir: For ``{loweringDataBaseDir}`` in paths.

    Returns:
        list[dict]: ``name``, ``longName``, ``description`` (``''`` if unset)
        and ``destDir`` (relative to the cruise directory, or to a lowering's
        directory for lowering-level entries), sorted by ``destDir``.
    """
    result = []
    for entry in entries or []:
        if str(entry.get('enable', '1')) != '1':
            continue
        if int(entry.get('cruiseOrLowering') or 0) != cruise_or_lowering:
            continue
        item = {field: (entry.get(field) or '').strip() for field in DIRECTORY_FIELDS}
        item['destDir'] = _fill_path(entry.get('destDir'), cruise_id, lowering_data_base_dir)
        result.append(item)
    return sorted(result, key=lambda item: item['destDir'].lower())


def _extent(value) -> Optional[dict]:
    """Return the cruise extent as a dict, or ``None`` if it isn't set."""
    if isinstance(value, str):
        try:
            value = json.loads(value) if value.strip() else None
        except ValueError:
            return None
    return value if isinstance(value, dict) and value else None


def build_cruise_readme_context(cruise_config: dict, collection_systems: list,  # pylint: disable=too-many-arguments,too-many-positional-arguments,too-many-locals
                                extra_directories: list, vessel: dict,
                                readme_fn: str, finalized_on: Optional[str] = None,
                                show_lowerings: bool = False) -> dict:
    """Return the variables a cruise README template is rendered with.

    Only enabled collection systems and extra directories are listed, and
    of each only the fields in :data:`DIRECTORY_FIELDS` plus its folder, so
    no credentials reach the template.

    Args:
        cruise_config: The current cruise's config (``OpenVDM.get_cruise_config()``).
        collection_systems: All collection system transfers, cruise- and
            lowering-level (``OpenVDM.get_collection_system_transfers()``).
        extra_directories: All extra directories (``OpenVDM.get_extra_directories()``).
        vessel: The vessel settings (``OpenVDM.get_vessel_config()``).
        readme_fn: The README's file name.
        finalized_on: When the cruise was finalized, if it has been.
        show_lowerings: Whether lowerings are used (``showLoweringComponents``).

    Returns:
        dict: The template variables:

        - ``cruise``: ``cruiseID``, ``cruiseName``, ``cruisePI``,
          ``cruiseLocation``, ``cruiseDescription``, ``cruiseStartDate``,
          ``cruiseEndDate``, ``cruiseStartPort``, ``cruiseEndPort`` (``''``
          when unset), ``cruiseExtent`` (``westernmost``, ``easternmost``,
          ``southernmost`` and ``northernmost``, or ``None``) and
          ``cruiseFinalizedOn`` (or ``None``).
        - ``vessel``: as ``vessel`` in ``openvdm.yaml``, unset fields left out.
        - ``collection_systems``, ``extra_directories``: the cruise-level
          folders, each with ``name``, ``longName``, ``description`` and
          ``destDir`` (relative to the cruise directory).
        - ``lowerings``: ``None`` unless lowerings are used; otherwise
          ``base_dir`` (relative to the cruise directory),
          ``collection_systems`` and ``extra_directories`` (``destDir``
          relative to a lowering's directory, ``<base_dir>/<loweringID>``)
          and ``config`` (the lowering config file's name).
        - ``files``: the cruise directory's OpenVDM files: ``readme``,
          ``cruise_config``, ``md5_summary``, ``md5_summary_md5`` and
          ``data_dashboard_manifest`` (``None`` without a ``Dashboard_Data``
          directory).
        - ``openvdm_version`` (``''`` if unknown) and ``generated_on`` (UTC,
          ISO 8601).
    """
    warehouse = cruise_config.get('warehouseConfig') or {}
    cruise_id = cruise_config.get('cruiseID') or ''
    lowering_data_base_dir = (warehouse.get('loweringDataBaseDir') or '').strip('/')

    cruise = {key: (cruise_config.get(key) or '') for key in (
        'cruiseID', 'cruiseName', 'cruisePI', 'cruiseLocation', 'cruiseDescription',
        'cruiseStartDate', 'cruiseEndDate', 'cruiseStartPort', 'cruiseEndPort')}
    cruise['cruiseExtent'] = _extent(cruise_config.get('cruiseExtent'))
    cruise['cruiseFinalizedOn'] = finalized_on or None

    cruise_extra_directories = _directories(extra_directories, 0, cruise_id, lowering_data_base_dir)

    dashboard_dir = next((entry['destDir'] for entry in cruise_extra_directories
                          if entry['name'] == 'Dashboard_Data'), None)
    manifest_fn = warehouse.get('dataDashboardManifestFn') or ''
    files = {
        'readme': readme_fn,
        'cruise_config': warehouse.get('cruiseConfigFn') or '',
        'md5_summary': warehouse.get('md5SummaryFn') or '',
        'md5_summary_md5': warehouse.get('md5SummaryMd5Fn') or '',
        'data_dashboard_manifest': f"{dashboard_dir}/{manifest_fn}" if dashboard_dir and manifest_fn else None,
    }

    lowerings = None
    if show_lowerings and lowering_data_base_dir:
        lowerings = {
            'base_dir': lowering_data_base_dir,
            'collection_systems': _directories(collection_systems, 1, cruise_id, lowering_data_base_dir),
            'extra_directories': _directories(extra_directories, 1, cruise_id, lowering_data_base_dir),
            'config': warehouse.get('loweringConfigFn') or '',
        }

    return {
        'cruise': cruise,
        'vessel': vessel or {},
        'collection_systems': _directories(collection_systems, 0, cruise_id, lowering_data_base_dir),
        'extra_directories': cruise_extra_directories,
        'lowerings': lowerings,
        'files': files,
        'openvdm_version': openvdm_version(),
        'generated_on': datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'),
    }


def render_readme(template_path: str, context: dict) -> str:
    """Render a README template, with the generated-file line at the top.

    The line is an HTML comment in a Markdown or HTML file (so it isn't
    shown when the file is rendered), plain text otherwise. Runs of blank
    lines, which a template's conditional blocks easily leave, become one.

    Args:
        template_path: The Jinja2 template.
        context: The variables, from :func:`build_cruise_readme_context`.

    Returns:
        str: The README's text.

    Raises:
        jinja2.TemplateError: If the template has an error.
        OSError: If the template can't be read.
    """
    env = jinja2.Environment(
        loader=jinja2.FileSystemLoader(os.path.dirname(template_path)),
        trim_blocks=True, lstrip_blocks=True, keep_trailing_newline=True,
        autoescape=False)
    body = env.get_template(os.path.basename(template_path)).render(**context)
    body = re.sub(r'\n[ \t]*\n(?:[ \t]*\n)+', '\n\n', body).strip('\n') + '\n'

    readme_fn = context.get('files', {}).get('readme', '')
    note = (f"{GENERATED_MARKER} {context.get('openvdm_version') or ''} on {context.get('generated_on')}"
            f" from {os.path.basename(template_path)}; changes to this file are overwritten.")
    note = note.replace('  ', ' ')
    if os.path.splitext(readme_fn)[1].lower() in ('.md', '.markdown', '.html', '.htm'):
        note = f"<!-- {note} -->"
    return f"{note}\n{body}"


def write_readme(path: str, text: str) -> tuple:
    """Write the README, unless a file there wasn't written by OpenVDM.

    The file is written to a temporary file next to it and then renamed, so
    a reader never sees half of it.

    Args:
        path: The README's path.
        text: Its text, from :func:`render_readme`.

    Returns:
        tuple[bool, str]: ``(True, '')`` when written; ``(False, reason)``
        when a file that OpenVDM didn't write is in the way, or writing fails.
    """
    if os.path.lexists(path):
        try:
            with open(path, encoding='utf-8', errors='replace') as file:
                first_line = file.readline()
        except OSError as exc:
            return False, f"Unable to read the existing {os.path.basename(path)}: {exc}"
        if not os.path.isfile(path) or GENERATED_MARKER not in first_line:
            return False, (f"{os.path.basename(path)} already exists in the cruise directory and "
                           "wasn't written by OpenVDM, so it wasn't replaced. Rename or remove it, "
                           "or set another cruiseReadme filename in openvdm.yaml.")

    tmp_path = f"{path}.tmp"
    try:
        with open(tmp_path, 'w', encoding='utf-8') as file:
            file.write(text)
        os.replace(tmp_path, path)
    except OSError as exc:
        logging.error("Unable to write %s: %s", path, exc)
        try:
            os.remove(tmp_path)
        except OSError:
            pass
        return False, f"Unable to write {os.path.basename(path)}: {exc}"
    return True, ''
